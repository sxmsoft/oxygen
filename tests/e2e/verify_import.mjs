#!/usr/bin/env node
// Headless e2e: Helium shortcut import (fixture Preferences -> import file ->
// quick links, once per content) and the live bookmarks-bar mirror (new tab
// widget, side panel, no duplication). Throwaway profiles only.
//
// Usage: node tests/e2e/verify_import.mjs [--binary PATH] [--shots DIR]
import { mkdtempSync, mkdirSync, rmSync, writeFileSync, readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { launchBrowser, closeBrowser, sleep, stageExtension } from './cdp.mjs';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const argv = process.argv.slice(2);
const opt = (name, def) => {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : def;
};
const binary = opt('--binary', process.env.HELIUM_BIN ?? '/opt/helium-browser-bin/helium');
const shots = resolve(opt('--shots', join(repo, 'dist/e2e')));
mkdirSync(shots, { recursive: true });

const results = [];
function check(name, ok, detail = '') {
  const d = typeof detail === 'string' ? detail : JSON.stringify(detail);
  results.push({ name, ok: !!ok, detail: d });
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${d ? '  — ' + d : ''}`);
}
async function step(name, fn) {
  try {
    await fn();
  } catch (e) {
    check(`${name}: unexpected error`, false, e.stack ?? String(e));
  }
}

// Fixture import file, generated by the same script `oxygen.sh import-shortcuts` uses.
const fixture = join(repo, 'tests/fixtures/helium-Preferences.json');
const withImport = stageExtension(join(repo, 'dist/extension'));
const tmp = mkdtempSync(join(tmpdir(), 'oxygen-e2e-import-'));
execFileSync('node', [join(repo, 'scripts/import_shortcuts.mjs'), '--preferences', fixture, '--out', join(tmp, 'import.json'), '--dist', withImport], { stdio: 'ignore' });
const expected = ['Video', 'Çalışma Alanı', 'Gizli Klasör', 'untitled.example', 'Long Title For A Banner Tool'];
const fixtureUrls = JSON.parse(readFileSync(join(tmp, 'import.json'), 'utf8')).shortcuts.map((s) => s.url);
const env = { LANG: 'en_US.UTF-8', LANGUAGE: 'en_US', LC_ALL: 'en_US.UTF-8' };

async function session(extDir, fn) {
  const profile = mkdtempSync(join(tmpdir(), 'oxygen-e2e-import-profile-'));
  const browser = await launchBrowser({ binary, profileDir: profile, extensions: [extDir], env });
  try {
    const { cdp } = browser;
    const swT = await cdp.waitForTarget((t) => t.type === 'service_worker' && t.url.endsWith('/background.js'));
    const sw = await cdp.attach(swT.targetId);
    await cdp.send('Runtime.runIfWaitingForDebugger', {}, sw).catch(() => {});
    await cdp.waitFor(sw, `typeof chrome !== 'undefined' && !!self.oxygenTest`);
    const EXT = (p) => `chrome-extension://${new URL(swT.url).host}/${p}`;
    await fn({ cdp, sw, ev: (e) => cdp.evaluate(sw, e), EXT });
  } finally {
    await closeBrowser(browser);
    rmSync(profile, { recursive: true, force: true });
  }
}
const links = `chrome.storage.local.get('oxygen.links').then(r => r['oxygen.links'] ?? [])`;

try {
  await session(withImport, async ({ cdp, sw, ev, EXT }) => {
    await step('import on first run', async () => {
      const got = await cdp.waitFor(sw, `${links}.then(l => l.length >= 5 && l)`, 10000);
      check('quick links = Helium shortcuts, same order and titles', JSON.stringify(got.map((l) => l.title)) === JSON.stringify(expected), got.map((l) => l.title));
      check('urls kept exactly (incl. #fragment)', JSON.stringify(got.map((l) => l.url)) === JSON.stringify(fixtureUrls));
      check('all marked source=helium', got.every((l) => l.source === 'helium'));
    });

    await step('idempotent / force', async () => {
      await ev(`${links}.then(l => chrome.storage.local.set({ 'oxygen.links': [...l.slice(1), { id: 'u1', title: 'Mine', url: 'https://mine.example/' }] }))`);
      const again = await ev(`self.oxygenTest.ingestShortcuts(false)`);
      const l1 = await ev(links);
      check('same import is not re-applied (a removed link stays removed)', !again.applied && l1.length === 5 && l1[0].title === expected[1], l1.map((l) => l.title));
      const forced = await ev(`self.oxygenTest.ingestShortcuts(true)`);
      const l2 = await ev(links);
      check('"Import from Helium" re-applies; user links kept after imported ones', forced.applied && JSON.stringify(l2.map((l) => l.title)) === JSON.stringify([...expected, 'Mine']), l2.map((l) => l.title));
    });

    let counts;
    await step('bookmarks fixture', async () => {
      counts = await ev(`(async () => {
        const dev = await chrome.bookmarks.create({ parentId: '1', title: 'Dev' });
        await chrome.bookmarks.create({ parentId: dev.id, title: 'Docs', url: 'https://docs.example/' });
        await chrome.bookmarks.create({ parentId: '1', index: 0, title: 'News', url: 'https://news.example/' });
        await chrome.bookmarks.create({ parentId: '2', title: 'PS5 Roms', url: 'https://ps.example/' });
        const n = (nodes) => nodes.reduce((a, x) => a + 1 + n(x.children ?? []), 0);
        return n(await chrome.bookmarks.getTree());
      })()`);
    });

    await step('new tab: bookmarks bar widget + imported links', async () => {
      const nt = await cdp.openPage(EXT('newtab.html'));
      await cdp.waitFor(nt.sessionId, `document.querySelectorAll('[data-testid=widget-links] .tile a').length === 6`, 10000);
      const tiles = await cdp.evaluate(nt.sessionId, `[...document.querySelectorAll('[data-testid=widget-links] .tile a .name')].map(e => e.textContent)`);
      check('new tab quick links show the Helium titles in order', JSON.stringify(tiles) === JSON.stringify([...expected, 'Mine']), tiles);
      const chips = await cdp.waitFor(nt.sessionId, `(() => { const c = [...document.querySelectorAll('[data-testid=widget-bookmarks] .chip')].map(e => e.textContent.trim()); return c.length === 3 && c; })()`, 8000);
      check('bookmarks widget mirrors the bar in order + All bookmarks', JSON.stringify(chips) === JSON.stringify(['News', '▸Dev', '☰All bookmarks']), chips);
      await cdp.evaluate(nt.sessionId, `document.querySelectorAll('[data-testid=bm-bar-folder]')[0].click() || true`);
      const inner = await cdp.waitFor(nt.sessionId, `document.querySelector('[data-testid=bm-drop] [data-testid=bm-link]')?.textContent.trim()`);
      check('folder opens with its children', inner === 'Docs', inner);
      const fav = await cdp.evaluate(nt.sessionId, `document.querySelector('[data-testid=bm-bar-link] img').getAttribute('src')`);
      check('favicons via _favicon API', String(fav).includes("/_favicon/?pageUrl="), fav);
      await ev(`chrome.bookmarks.create({ parentId: '1', title: 'Live', url: 'https://live.example/' })`);
      const live = await cdp.waitFor(nt.sessionId, `[...document.querySelectorAll('[data-testid=widget-bookmarks] .chip')].some(e => e.textContent.includes('Live'))`, 5000);
      check('bookmark changes show up live', live);
      await cdp.evaluate(nt.sessionId, `document.querySelectorAll('[data-testid=bm-bar-folder]')[1].click() || true`);
      await sleep(400);
      writeFileSync(join(shots, '20-newtab-helium-import.png'), await cdp.screenshot(nt.sessionId));
      const after = await ev(`chrome.bookmarks.getTree().then(t => { const n = (nodes) => nodes.reduce((a, x) => a + 1 + n(x.children ?? []), 0); return n(t); })`);
      check('bookmarks are not copied or duplicated', after === counts + 1, { before: counts, after });
    });

    await step('saved layout gets the bookmarks widget once', async () => {
      await ev(`chrome.storage.local.set({ 'oxygen.newtab.layout': [{ id: 'w-clock', type: 'clock', x: 0, y: 0, w: 4, h: 2, settings: {} }] }).then(() => chrome.storage.local.remove('oxygen.newtab.added.bookmarks'))`);
      const nt = await cdp.openPage(EXT('newtab.html'));
      const added = await cdp.waitFor(sw, `chrome.storage.local.get('oxygen.newtab.layout').then(r => r['oxygen.newtab.layout'].some(w => w.type === 'bookmarks'))`, 8000);
      check('old layout migrated (bookmarks widget added)', added);
      await ev(`chrome.storage.local.set({ 'oxygen.newtab.layout': [{ id: 'w-clock', type: 'clock', x: 0, y: 0, w: 4, h: 2, settings: {} }] })`);
      await cdp.send('Page.reload', {}, nt.sessionId);
      await sleep(1500);
      const stays = await ev(`chrome.storage.local.get('oxygen.newtab.layout').then(r => !r['oxygen.newtab.layout'].some(w => w.type === 'bookmarks'))`);
      check('removing it afterwards sticks', stays);
    });

    await step('side panel bookmarks + import button', async () => {
      const sp = await cdp.openPage(EXT('sidepanel.html'));
      await cdp.waitFor(sp.sessionId, `document.querySelector('[data-testid=sp-tab-bookmarks]') !== null`);
      // the page may still be hydrating: click until the bookmarks tab is shown
      await cdp.waitFor(sp.sessionId, `document.querySelector('[data-testid=sp-bookmarks]') !== null || (document.querySelector('[data-testid=sp-tab-bookmarks]').click(), false)`);
      const rows = await cdp.waitFor(sp.sessionId, `(() => { const r = [...document.querySelectorAll('[data-testid=sp-bookmarks] [data-testid=bm-tree] > li > .bm-row')].map(e => e.textContent.trim()); return r.length >= 4 && r; })()`);
      check('side panel lists the bar (order) and All bookmarks', rows[0] === 'News' && rows.at(-1).includes('All bookmarks') && rows[1].includes('Dev'), rows);
      await cdp.evaluate(sp.sessionId, `[...document.querySelectorAll('[data-testid=bm-folder]')].at(-1).click() || true`);
      const ps = await cdp.waitFor(sp.sessionId, `[...document.querySelectorAll('[data-testid=bm-link]')].some(e => e.textContent.includes('PS5 Roms'))`);
      check('All bookmarks expands to Other bookmarks', ps);
      writeFileSync(join(shots, '21-sidepanel-bookmarks.png'), await cdp.screenshot(sp.sessionId));
    });

    await step('Control Center import card', async () => {
      const cc = await cdp.openPage(EXT('index.html#workspaces'));
      await cdp.waitFor(cc.sessionId, `document.querySelector('[data-testid=cc-helium-import-btn]') !== null`, 10000);
      await cdp.evaluate(cc.sessionId, `document.querySelector('[data-testid=cc-helium-import-btn]').click() || true`);
      const msg = await cdp.waitFor(cc.sessionId, `document.querySelector('[data-testid=cc-helium-import-msg]')?.textContent`);
      check('CC "Import from Helium" reports the import', /Imported 5 Helium shortcut/.test(msg), msg);
      await cdp.evaluate(cc.sessionId, `document.querySelector('[data-testid=cc-helium-import]').scrollIntoView() || true`);
      writeFileSync(join(shots, '22-cc-helium-import.png'), await cdp.screenshot(cc.sessionId));
    });
  });

  // Without an import file: no crash, most-visited fallback (empty in a fresh profile).
  const without = stageExtension(join(repo, 'dist/extension'));
  await session(without, async ({ cdp, ev, EXT }) => {
    await step('fallback without import file', async () => {
      const r = await ev(`self.oxygenTest.ingestShortcuts(true)`);
      check('no import file -> topSites fallback, reported honestly', r.ok && (r.source === 'topsites' || r.source === 'none'), r);
      const nt = await cdp.openPage(EXT('newtab.html'));
      await cdp.waitFor(nt.sessionId, `document.querySelector('[data-testid=widget-bookmarks]') !== null`, 8000);
      const empty = await cdp.waitFor(nt.sessionId, `document.querySelector('[data-testid=widget-bookmarks] .empty')?.textContent`, 5000);
      check('empty bookmarks bar is labelled', !!empty, empty);
    });
  });
  rmSync(dirname(without), { recursive: true, force: true });
} finally {
  rmSync(dirname(withImport), { recursive: true, force: true });
  rmSync(tmp, { recursive: true, force: true });
}

const passed = results.filter((r) => r.ok).length;
writeFileSync(join(shots, 'results-import.json'), JSON.stringify(results, null, 2));
console.log(`\n${passed}/${results.length} import checks passed; screenshots in ${shots}`);
process.exit(passed === results.length ? 0 : 1);
